-- GodGram C# migration / PostgreSQL 15+
-- Standalone database: NO SQLite and NO Python runtime.
CREATE TABLE IF NOT EXISTS users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 phone TEXT UNIQUE,
 username TEXT UNIQUE,
 nft_username TEXT,
 nft_number TEXT,
 first_name TEXT NOT NULL DEFAULT '', last_name TEXT NOT NULL DEFAULT '',
 name TEXT NOT NULL DEFAULT '', bio TEXT NOT NULL DEFAULT '',
 avatar TEXT NOT NULL DEFAULT '', avv INT NOT NULL DEFAULT 0,
 is_admin BOOLEAN NOT NULL DEFAULT FALSE, is_service BOOLEAN NOT NULL DEFAULT FALSE,
 is_bot BOOLEAN NOT NULL DEFAULT FALSE, bot_owner BIGINT NOT NULL DEFAULT 0,
 bot_token TEXT UNIQUE, bot_script JSONB NOT NULL DEFAULT '{}'::jsonb,
 bot_desc TEXT NOT NULL DEFAULT '', frozen BOOLEAN NOT NULL DEFAULT FALSE,
 deleted BOOLEAN NOT NULL DEFAULT FALSE,
 created DOUBLE PRECISION NOT NULL DEFAULT EXTRACT(EPOCH FROM now()),
 last_seen DOUBLE PRECISION NOT NULL DEFAULT 0,
 premium_until DOUBLE PRECISION NOT NULL DEFAULT 0,
 balance BIGINT NOT NULL DEFAULT 0, rating BIGINT NOT NULL DEFAULT 0,
 banner_color INT NOT NULL DEFAULT -1, banner_pattern TEXT NOT NULL DEFAULT '',
 emoji_status TEXT NOT NULL DEFAULT '',
 birthday TEXT NOT NULL DEFAULT '', address TEXT NOT NULL DEFAULT '',
 work_from TEXT NOT NULL DEFAULT '', work_to TEXT NOT NULL DEFAULT '',
 pchannel BIGINT NOT NULL DEFAULT 0, status_text TEXT NOT NULL DEFAULT '',
 status_nft BIGINT NOT NULL DEFAULT 0, boost_inf BOOLEAN NOT NULL DEFAULT FALSE,
 cloud_hash TEXT NOT NULL DEFAULT '', cloud_salt TEXT NOT NULL DEFAULT '',
 cloud_hint TEXT NOT NULL DEFAULT '', uorder JSONB NOT NULL DEFAULT '[]'::jsonb,
 umain JSONB NOT NULL DEFAULT '[]'::jsonb
);
CREATE TABLE IF NOT EXISTS sessions (
 token TEXT PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 created DOUBLE PRECISION NOT NULL DEFAULT EXTRACT(EPOCH FROM now())
);
CREATE INDEX IF NOT EXISTS sessions_user_idx ON sessions(user_id);
CREATE TABLE IF NOT EXISTS login_codes(
 phone TEXT PRIMARY KEY, code_hash TEXT NOT NULL, sent_at DOUBLE PRECISION NOT NULL,
 expires_at DOUBLE PRECISION NOT NULL, attempts INT NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS pending_passwords(
 token TEXT PRIMARY KEY,user_id BIGINT NOT NULL REFERENCES users(id),
 expires_at DOUBLE PRECISION NOT NULL, attempts INT NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS registration_tokens(
 token TEXT PRIMARY KEY, phone TEXT NOT NULL,
 expires_at DOUBLE PRECISION NOT NULL
);
CREATE TABLE IF NOT EXISTS chats (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 kind TEXT NOT NULL CHECK (kind IN ('private','saved','group','channel')),
 title TEXT NOT NULL DEFAULT '', avatar TEXT NOT NULL DEFAULT '', avv INT NOT NULL DEFAULT 0,
 owner BIGINT REFERENCES users(id), private_peer BIGINT REFERENCES users(id),
 created DOUBLE PRECISION NOT NULL DEFAULT EXTRACT(EPOCH FROM now()),
 frozen BOOLEAN NOT NULL DEFAULT FALSE, descr TEXT NOT NULL DEFAULT '',
 handle TEXT UNIQUE, sign BOOLEAN NOT NULL DEFAULT FALSE,
 bcolor INT NOT NULL DEFAULT -1, bpattern TEXT NOT NULL DEFAULT '',
 estatus TEXT NOT NULL DEFAULT '', deleted BOOLEAN NOT NULL DEFAULT FALSE,
 pub BOOLEAN NOT NULL DEFAULT TRUE, boost_extra INT NOT NULL DEFAULT 0,
 discussion_chat_id BIGINT NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX IF NOT EXISTS uniq_private_pair ON chats(owner,private_peer) WHERE kind='private';
CREATE UNIQUE INDEX IF NOT EXISTS uniq_saved_chat ON chats(owner) WHERE kind='saved';
CREATE TABLE IF NOT EXISTS members(
 chat_id BIGINT NOT NULL REFERENCES chats(id) ON DELETE CASCADE,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 last_read BIGINT NOT NULL DEFAULT 0,
 PRIMARY KEY(chat_id,user_id)
);
CREATE INDEX IF NOT EXISTS members_by_user ON members(user_id);
CREATE TABLE IF NOT EXISTS messages(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 chat_id BIGINT NOT NULL REFERENCES chats(id) ON DELETE CASCADE,
 user_id BIGINT NOT NULL REFERENCES users(id),
 text TEXT NOT NULL DEFAULT '',
 ts DOUBLE PRECISION NOT NULL DEFAULT EXTRACT(EPOCH FROM now()),
 gift_id BIGINT NOT NULL DEFAULT 0, media_key TEXT NOT NULL DEFAULT '',
 media_kind TEXT NOT NULL DEFAULT '', media_dur INT NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS messages_chat_idx ON messages(chat_id,id DESC);
CREATE TABLE IF NOT EXISTS pins(
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 chat_id BIGINT NOT NULL REFERENCES chats(id) ON DELETE CASCADE,
 ts DOUBLE PRECISION NOT NULL DEFAULT EXTRACT(EPOCH FROM now()),
 PRIMARY KEY(user_id,chat_id)
);
CREATE TABLE IF NOT EXISTS media(
 key TEXT PRIMARY KEY, mime TEXT NOT NULL, data BYTEA NOT NULL,
 owner BIGINT NOT NULL REFERENCES users(id), ts DOUBLE PRECISION NOT NULL DEFAULT EXTRACT(EPOCH FROM now())
);
CREATE TABLE IF NOT EXISTS gifts(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name TEXT NOT NULL, price BIGINT NOT NULL DEFAULT 0,
 model TEXT NOT NULL DEFAULT 'extrude', glyph TEXT NOT NULL DEFAULT '🎁',
 color TEXT NOT NULL DEFAULT '#2aabee', anim TEXT NOT NULL DEFAULT 'spin',
 supply BIGINT NOT NULL DEFAULT 0, sold BIGINT NOT NULL DEFAULT 0,
 active BOOLEAN NOT NULL DEFAULT TRUE, created DOUBLE PRECISION NOT NULL DEFAULT EXTRACT(EPOCH FROM now())
);
CREATE TABLE IF NOT EXISTS user_gifts(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 gift_id BIGINT NOT NULL REFERENCES gifts(id),
 owner_id BIGINT REFERENCES users(id), from_id BIGINT REFERENCES users(id),
 note TEXT NOT NULL DEFAULT '', number BIGINT NOT NULL DEFAULT 0,
 ts DOUBLE PRECISION NOT NULL DEFAULT EXTRACT(EPOCH FROM now()),
 listed BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS user_gifts_owner_idx ON user_gifts(owner_id,id);
CREATE TABLE IF NOT EXISTS nft_usernames(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 handle TEXT NOT NULL UNIQUE, owner_id BIGINT REFERENCES users(id),
 created DOUBLE PRECISION NOT NULL DEFAULT EXTRACT(EPOCH FROM now()),
 active BOOLEAN NOT NULL DEFAULT TRUE, price BIGINT NOT NULL DEFAULT 0,
 issued DOUBLE PRECISION NOT NULL DEFAULT 0, listed BOOLEAN NOT NULL DEFAULT FALSE,
 list_price BIGINT NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS nft_numbers(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 number TEXT NOT NULL UNIQUE, owner_id BIGINT REFERENCES users(id),
 created DOUBLE PRECISION NOT NULL DEFAULT EXTRACT(EPOCH FROM now()),
 listed BOOLEAN NOT NULL DEFAULT FALSE, list_price BIGINT NOT NULL DEFAULT 0,
 price BIGINT NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS nft_colls(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name TEXT NOT NULL, glyph TEXT NOT NULL DEFAULT '',
 supply BIGINT NOT NULL DEFAULT 0, minted BIGINT NOT NULL DEFAULT 0,
 price BIGINT NOT NULL DEFAULT 100, models JSONB NOT NULL DEFAULT '[]'::jsonb,
 active BOOLEAN NOT NULL DEFAULT TRUE,
 created DOUBLE PRECISION NOT NULL DEFAULT EXTRACT(EPOCH FROM now())
);
CREATE TABLE IF NOT EXISTS nft_items(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 coll_id BIGINT REFERENCES nft_colls(id), number BIGINT NOT NULL,
 owner_id BIGINT REFERENCES users(id), model TEXT, backdrop TEXT, symbol TEXT,
 anim TEXT NOT NULL DEFAULT 'spin', price BIGINT NOT NULL DEFAULT 0,
 listed BOOLEAN NOT NULL DEFAULT FALSE, from_id BIGINT REFERENCES users(id),
 ts DOUBLE PRECISION NOT NULL DEFAULT EXTRACT(EPOCH FROM now()),
 UNIQUE(coll_id,number)
);
CREATE INDEX IF NOT EXISTS nft_items_owner_idx ON nft_items(owner_id,id);
CREATE TABLE IF NOT EXISTS badge_defs(
 key TEXT PRIMARY KEY, title TEXT NOT NULL, descr TEXT NOT NULL DEFAULT '',
 color TEXT NOT NULL DEFAULT '', kind TEXT NOT NULL DEFAULT 'verify',
 icon TEXT NOT NULL DEFAULT '', sort INT NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS entity_badges(
 kind TEXT NOT NULL, tid BIGINT NOT NULL, bkey TEXT NOT NULL REFERENCES badge_defs(key),
 ts DOUBLE PRECISION NOT NULL DEFAULT EXTRACT(EPOCH FROM now()),
 PRIMARY KEY(kind,tid,bkey)
);
CREATE TABLE IF NOT EXISTS boosts(
 chat_id BIGINT NOT NULL REFERENCES chats(id) ON DELETE CASCADE,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 ts DOUBLE PRECISION NOT NULL DEFAULT EXTRACT(EPOCH FROM now()),
 PRIMARY KEY(chat_id,user_id)
);
CREATE TABLE IF NOT EXISTS reports(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 reporter_id BIGINT NOT NULL REFERENCES users(id),
 tkind TEXT NOT NULL, tid BIGINT NOT NULL, reason TEXT NOT NULL,
 text TEXT NOT NULL DEFAULT '', status TEXT NOT NULL DEFAULT 'open',
 ts DOUBLE PRECISION NOT NULL DEFAULT EXTRACT(EPOCH FROM now()),
 note TEXT NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS stories(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id), kind TEXT NOT NULL,
 media_key TEXT NOT NULL DEFAULT '', text TEXT NOT NULL DEFAULT '',
 bg INT NOT NULL DEFAULT 0,
 ts DOUBLE PRECISION NOT NULL DEFAULT EXTRACT(EPOCH FROM now()), expires DOUBLE PRECISION NOT NULL
);
CREATE TABLE IF NOT EXISTS story_views(
 story_id BIGINT NOT NULL REFERENCES stories(id) ON DELETE CASCADE,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 ts DOUBLE PRECISION NOT NULL DEFAULT EXTRACT(EPOCH FROM now()),
 PRIMARY KEY(story_id,user_id)
);
CREATE TABLE IF NOT EXISTS tx(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id),
 amount BIGINT NOT NULL, kind TEXT NOT NULL, note TEXT NOT NULL DEFAULT '',
 ts DOUBLE PRECISION NOT NULL DEFAULT EXTRACT(EPOCH FROM now())
);
CREATE TABLE IF NOT EXISTS rating_log(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id), delta BIGINT NOT NULL,
 kind TEXT NOT NULL, note TEXT NOT NULL DEFAULT '',
 from_id BIGINT NOT NULL DEFAULT 0, ref_id BIGINT NOT NULL DEFAULT 0,
 ts DOUBLE PRECISION NOT NULL DEFAULT EXTRACT(EPOCH FROM now())
);
CREATE TABLE IF NOT EXISTS star_checks(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code TEXT NOT NULL UNIQUE, creator_id BIGINT NOT NULL REFERENCES users(id),
 amount BIGINT NOT NULL, max_uses INT NOT NULL DEFAULT 1,
 used INT NOT NULL DEFAULT 0, note TEXT NOT NULL DEFAULT '',
 active BOOLEAN NOT NULL DEFAULT TRUE,
 created DOUBLE PRECISION NOT NULL DEFAULT EXTRACT(EPOCH FROM now()),
 expires DOUBLE PRECISION NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS star_check_claims(
 check_id BIGINT NOT NULL REFERENCES star_checks(id),
 user_id BIGINT NOT NULL REFERENCES users(id),
 ts DOUBLE PRECISION NOT NULL DEFAULT EXTRACT(EPOCH FROM now()),
 PRIMARY KEY(check_id,user_id)
);
CREATE TABLE IF NOT EXISTS bot_updates(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 bot_id BIGINT NOT NULL REFERENCES users(id), chat_id BIGINT REFERENCES chats(id),
 from_id BIGINT REFERENCES users(id), text TEXT NOT NULL DEFAULT '',
 ts DOUBLE PRECISION NOT NULL DEFAULT EXTRACT(EPOCH FROM now())
);
